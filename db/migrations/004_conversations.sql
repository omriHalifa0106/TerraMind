-- Conversation memory: what the previous turn of a chat produced, so a follow-up message
-- ("make it 4 hours", "add a winery", "a different trail") edits the trip instead of starting over.
-- Written and read by the API around each graph run (terramind/conversations.py); agents get it
-- in the graph input and never touch this table.
CREATE TABLE IF NOT EXISTS conversations (
    thread_id  TEXT PRIMARY KEY,                 -- generated by the browser, one per chat
    state      JSONB NOT NULL,                   -- terramind.schemas.PreviousTurn
    turns      INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS conversations_updated_idx ON conversations (updated_at);
